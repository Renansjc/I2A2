    async def _perform_statistical_analysis(self, query_result: Dict[str, Any]) -> Dict[str, Any]:
        """Perform statistical analysis on the data"""
        try:
            data = query_result.get('data', [])
            
            if not data:
                return {'message': 'Dados insuficientes para análise estatística'}
            
            analysis = {
                'record_count': len(data),
                'data_quality': 'Boa' if len(data) > 10 else 'Limitada'
            }
            
            # Find numeric columns for statistical analysis
            numeric_columns = []
            for key, value in (data[0].items() if data else []):
                if isinstance(value, (int, float)):
                    numeric_columns.append(key)
            
            # Perform statistical calculations
            for col in numeric_columns:
                values = [row.get(col, 0) for row in data if row.get(col) is not None and row.get(col) != 0]
                if values and len(values) > 1:
                    mean_val = sum(values) / len(values)
                    variance = sum((x - mean_val) ** 2 for x in values) / len(values)
                    std_dev = variance ** 0.5
                    
                    analysis[f'{col}_statistics'] = {
                        'mean': mean_val,
                        'std_deviation': std_dev,
                        'coefficient_variation': (std_dev / mean_val) * 100 if mean_val != 0 else 0,
                        'range': max(values) - min(values),
                        'median': sorted(values)[len(values) // 2]
                    }
            
            # Identify trends if temporal data is available
            if any('data' in col.lower() or 'date' in col.lower() for col in (data[0].keys() if data else [])):
                analysis['temporal_analysis'] = 'Dados temporais identificados - análise de tendência possível'
            
            return analysis
            
        except Exception as e:
            self.logger.error("Error performing statistical analysis", error=str(e))
            return {'error': 'Erro na análise estatística'}
    
