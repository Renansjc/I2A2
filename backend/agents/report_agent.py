    async def _assess_urgency_level(self, insights: DataInsights) -> str:
        """Assess urgency level based on insights"""
        try:
            urgency_score = 0
            
            # Check for high-impact findings
            if insights.business_impact:
                impact_indicators = str(insights.business_impact).lower()
                if any(keyword in impact_indicators for keyword in ['crítico', 'urgente', 'alto', 'significativo']):
                    urgency_score += 2
                elif any(keyword in impact_indicators for keyword in ['moderado', 'médio']):
                    urgency_score += 1
            
            # Check strategic implications
            if insights.strategic_implications:
                strategic_text = ' '.join(insights.strategic_implications).lower()
                if any(keyword in strategic_text for keyword in ['imediato', 'urgente', 'crítico']):
                    urgency_score += 2
                elif any(keyword in strategic_text for keyword in ['importante', 'relevante']):
                    urgency_score += 1
            
            # Check confidence level
            if insights.confidence_level > 0.8:
                urgency_score += 1
            
            # Determine urgency level
            if urgency_score >= 4:
                return 'Alto'
            elif urgency_score >= 2:
                return 'Médio'
            else:
                return 'Baixo'
                
        except Exception as e:
            self.logger.error("Error assessing urgency level", error=str(e))
            return 'Médio'
    
