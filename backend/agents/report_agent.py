class Recommendation:
    """Actionable business recommendation"""
    
    def __init__(self, title: str, description: str, priority: str,
                 risk_assessment: str, resource_requirements: Dict[str, Any],
                 timeline: str, expected_impact: str):
        self.title = title
        self.description = description
        self.priority = priority
        self.risk_assessment = risk_assessment
        self.resource_requirements = resource_requirements
        self.timeline = timeline
        self.expected_impact = expected_impact
    
    @classmethod
    def list_from_llm_response(cls, llm_response: LLMResponse) -> List['Recommendation']:
        """Create list of recommendations from LLM response"""
        try:
            data = json.loads(llm_response.content)
            recommendations = []
            
            for rec_data in data.get('recommendations', []):
                recommendations.append(cls(
                    title=rec_data.get('title', ''),
                    description=rec_data.get('description', ''),
                    priority=rec_data.get('priority', 'Medium'),
                    risk_assessment=rec_data.get('risk_assessment', ''),
                    resource_requirements=rec_data.get('resource_requirements', {}),
                    timeline=rec_data.get('timeline', ''),
                    expected_impact=rec_data.get('expected_impact', '')
                ))
            
            return recommendations
        except (json.JSONDecodeError, KeyError):
            return []

